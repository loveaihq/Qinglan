# Generates crates/qinglan-engine/src/html/quirks_data.rs from the DOCTYPE rules of the "initial" insertion mode
# (docs/spec/html-parsing.txt, HTML 13.2.6.4.1). Run: python -I tools/gen_quirks.py
import io, re
lines = io.open('docs/spec/html-parsing.txt', encoding='utf-8').read().split('\n')
start = next(i for i, l in enumerate(lines) if l.startswith('13.2.6.4.1 The "initial"') and i > 1000)
end = next(i for i, l in enumerate(lines) if l.startswith('13.2.6.4.2 The "before html"') and i > start)
quirks_pub_exact, quirks_sys_exact, quirks_pub_prefix = [], [], []
quirks_pub_prefix_sysmissing, limited_prefix, limited_prefix_syspresent = [], [], []
in_limited = False
for l in lines[start:end]:
    if 'limited-quirks' in l:
        in_limited = True
    m = re.match(r'^\s*The public identifier starts with: "(.*)"\s*$', l)
    if m:
        (limited_prefix if in_limited else quirks_pub_prefix).append(m.group(1)); continue
    m = re.match(r'^\s*The public identifier is set to: "(.*)"\s*$', l)
    if m:
        quirks_pub_exact.append(m.group(1)); continue
    m = re.match(r'^\s*The system identifier is set to: "(.*)"\s*$', l)
    if m:
        quirks_sys_exact.append(m.group(1)); continue
    m = re.match(r'^\s*The system identifier is missing or the empty string, and the public identifier starts with: "(.*)"\s*$', l)
    if m:
        quirks_pub_prefix_sysmissing.append(m.group(1)); continue
    m = re.match(r'^\s*The system identifier is neither missing nor the empty string, and the public identifier starts with: "(.*)"\s*$', l)
    if m:
        limited_prefix_syspresent.append(m.group(1)); continue
def arr(name, items):
    return 'pub static %s: &[&str] = &[\n%s];\n\n' % (name, ''.join('    "%s",\n' % s for s in items))
out = '//! Generated by tools/gen_quirks.py from HTML 13.2.6.4.1 (the "initial" insertion mode). Do not edit.\n//! All comparisons are ASCII case-insensitive (the strings below are lower-cased at use).\n\n'
out += arr('QUIRKS_PUBLIC_EXACT', quirks_pub_exact) + arr('QUIRKS_SYSTEM_EXACT', quirks_sys_exact)
out += arr('QUIRKS_PUBLIC_PREFIX', quirks_pub_prefix) + arr('QUIRKS_PUBLIC_PREFIX_IF_SYSTEM_MISSING', quirks_pub_prefix_sysmissing)
out += arr('LIMITED_PUBLIC_PREFIX', limited_prefix) + arr('LIMITED_PUBLIC_PREFIX_IF_SYSTEM_PRESENT', limited_prefix_syspresent)
io.open('crates/qinglan-engine/src/html/quirks_data.rs', 'w', encoding='utf-8', newline='\n').write(out)
print(len(quirks_pub_exact), len(quirks_sys_exact), len(quirks_pub_prefix), len(quirks_pub_prefix_sysmissing), len(limited_prefix), len(limited_prefix_syspresent))
