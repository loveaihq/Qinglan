#!/usr/bin/env python3
"""Generate crates/qinglan-engine/src/fonts/brotli_tables.rs from google/brotli's c/common/{transform.c,context.c}
(MIT; RFC 7932 appendix B and section 7.1). Usage: gen_brotli_tables.py <transform.c> <context.c> <out.rs>"""
import re, sys

tsrc = open(sys.argv[1], encoding="utf-8").read()
csrc = open(sys.argv[2], encoding="utf-8").read()

def strip_comments(s):
    return re.sub(r"/\*.*?\*/", "", s, flags=re.S)

def c_unescape(lit):
    out = bytearray(); i = 0
    while i < len(lit):
        c = lit[i]
        if c != "\\":
            out += c.encode("utf-8"); i += 1; continue
        i += 1; c = lit[i]
        if c in "01234567":
            j = i
            while j < len(lit) and j < i + 3 and lit[j] in "01234567": j += 1
            out.append(int(lit[i:j], 8)); i = j
        elif c == "x":
            j = i + 1
            while j < len(lit) and j < i + 3 and lit[j] in "0123456789abcdefABCDEF": j += 1
            out.append(int(lit[i + 1:j], 16)); i = j
        else:
            out.append({"n": 10, "t": 9, '"': 34, "'": 39, "\\": 92}[c]); i += 1
    return bytes(out)

body = strip_comments(tsrc)
m = re.search(r"kPrefixSuffix\[\d+\]\s*=(.*?);", body, re.S)
BSL = chr(92)
lits = re.findall('"((?:[^"' + BSL + BSL + ']|' + BSL + BSL + '.)*)"', m.group(1))
ps = b"".join(c_unescape(l) for l in lits) + bytes(1)  # the implicit trailing NUL
m = re.search(r"kPrefixSuffixMap\[\d+\]\s*=\s*\{(.*?)\}", body, re.S)
pmap = [int(x, 16) for x in re.findall(r"0x[0-9A-Fa-f]+", m.group(1))]
entries = []
for off in pmap:
    n = ps[off]
    entries.append(ps[off + 1:off + 1 + n])
names = {}
for mm in re.finditer(r"(BROTLI_TRANSFORM_\w+)\s*=\s*(\d+)", open(sys.argv[1].replace("transform.c", "transform.h"), encoding="utf-8").read()):
    names[mm.group(1)] = int(mm.group(2))
m = re.search(r"kTransformsData\[\]\s*=\s*\{(.*?)\};", body, re.S)
vals = [t.strip() for t in m.group(1).split(",") if t.strip()]
vals = [names[v] if v in names else int(v) for v in vals]
assert len(vals) == 121 * 3, len(vals)
trans = [tuple(vals[i:i + 3]) for i in range(0, len(vals), 3)]

m = re.search(r"_kBrotliContextLookupTable\[2048\]\s*=\s*\{(.*?)\};", strip_comments(csrc), re.S)
ctx = [int(x) for x in re.findall(r"\d+", m.group(1))]
assert len(ctx) == 2048
# Modes 0 (LSB6), 1 (MSB6) and 3 (Signed) are formulas; check them against the table, keep UTF8's tables.
sg = lambda b: 0 if b == 0 else 1 if b < 16 else 2 if b < 64 else 3 if b < 128 else 4 if b < 192 else 5 if b < 240 else 6 if b < 255 else 7
for b in range(256):
    assert ctx[b] == b & 63 and ctx[256 + b] == 0
    assert ctx[512 + b] == b >> 2 and ctx[768 + b] == 0
    assert ctx[1536 + b] == sg(b) << 3 and ctx[1792 + b] == sg(b), b
utf8 = ctx[1024:1536]

o = ["// Generated by tools/gen_brotli_tables.py from google/brotli c/common/transform.c and context.c (MIT, see",
     "// tests/fixtures/brotli/LICENSE). RFC 7932 appendix B (transforms) and section 7.1 (UTF8 context lookup).", ""]
o.append("/// Prefixes and suffixes of the transforms (the strings of RFC 7932 appendix B).")
o.append("pub const AFFIXES: [&[u8]; %d] = [" % len(entries))
for e in entries:
    BS = chr(92)
    o.append('    b"%s",' % ''.join((BS + 'x%02x' % b) if (b < 32 or b > 126 or chr(b) in ('"', BS)) else chr(b) for b in e))
o.append("];")
o.append("")
o.append("/// (prefix, transform type, suffix) of the 121 transforms; the type is `BROTLI_TRANSFORM_*` (0 identity, 1..=9 omit last,")
o.append("/// 10 uppercase first, 11 uppercase all, 12..=20 omit first).")
o.append("pub const TRANSFORMS: [(u8, u8, u8); 121] = [")
for t in trans:
    assert t[1] <= 20
    o.append("    (%d, %d, %d)," % t)
o.append("];")
o.append("")
for name, data in (("UTF8_LUT0", utf8[:256]), ("UTF8_LUT1", utf8[256:])):
    o.append("pub const %s: [u8; 256] = [" % name)
    for i in range(0, 256, 16):
        o.append("    " + ", ".join(str(x) for x in data[i:i + 16]) + ",")
    o.append("];")
    o.append("")
open(sys.argv[3], "w", newline="\n").write("\n".join(o))
print(len(entries), "affixes,", len(trans), "transforms")
