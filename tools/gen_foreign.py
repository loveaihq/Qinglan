# Generates crates/qinglan-engine/src/html/foreign_data.rs: the SVG tag-name and attribute-name case fix-up tables
# of the tree builder (docs/spec/html-parsing.txt, HTML 13.2.6.1 and 13.2.6.5). Run: python -I tools/gen_foreign.py
import io
lines = io.open('docs/spec/html-parsing.txt', encoding='utf-8').read().split('\n')
def table(header_prefix, last_key):
    i = next(k for k, l in enumerate(lines) if l.strip().startswith(header_prefix) and k > 3000)
    out = []
    for l in lines[i + 1:]:
        parts = l.split()
        if len(parts) != 2:
            break
        out.append((parts[0], parts[1]))
        if parts[0] == last_key:
            break
    return out
tags = table('Tag name Element name', 'textpath')
attrs = table('Attribute name on token', 'zoomandpan')
o = '//! Generated by tools/gen_foreign.py from HTML 13.2.6.1 and 13.2.6.5. Do not edit.\n\n'
o += '/// SVG element names: (lower-case name on the token, name on the element).\npub static SVG_TAGS: &[(&str, &str)] = &[\n' + ''.join('    ("%s", "%s"),\n' % t for t in tags) + '];\n\n'
o += '/// SVG attribute names: (lower-case name on the token, name on the element).\npub static SVG_ATTRS: &[(&str, &str)] = &[\n' + ''.join('    ("%s", "%s"),\n' % t for t in attrs) + '];\n'
io.open('crates/qinglan-engine/src/html/foreign_data.rs', 'w', encoding='utf-8', newline='\n').write(o)
print(len(tags), len(attrs))
