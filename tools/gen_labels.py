# Generates crates/qinglan-engine/src/encoding/labels.rs from docs/spec/encoding.html (WHATWG Encoding 4.2).
# Run: python -I tools/gen_labels.py
import re, io
s = io.open('docs/spec/encoding.html', encoding='utf-8').read()
start = s.index('The Encoding</a>')
end = s.index('</table>', start)
region = s[start:end]
rows = re.split(r'<tr>', region)
name = None
pairs = []
for r in rows:
    m = re.search(r'<td(?: rowspan="\d+")?>\s*<a [^>]*>([^<]+)</a>', r)
    if m:
        name = m.group(1).strip()
    l = re.search(r'<td>"<code>([^<]+)</code>"', r)
    if l and name:
        pairs.append((l.group(1), name))
names = sorted(set(n for _, n in pairs))
out = io.StringIO()
out.write('//! Generated by tools/gen_labels.py from the WHATWG Encoding Standard, section 4.2. Do not edit.\n\n')
out.write('/// (label, encoding name), labels already lower-case.\n')
out.write('pub static LABELS: &[(&str, &str)] = &[\n')
for lab, n in sorted(pairs):
    out.write('    ("%s", "%s"),\n' % (lab, n))
out.write('];\n')
io.open('crates/qinglan-engine/src/encoding/labels.rs', 'w', encoding='utf-8', newline='\n').write(out.getvalue())
print(len(pairs), 'labels,', len(names), 'encodings:', ' '.join(names))
