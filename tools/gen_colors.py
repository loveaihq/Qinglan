# Generates crates/qinglan-engine/src/css/color_names.rs from CSS Color 4 section 6.1 (named colors).
# Run: python -I tools/gen_colors.py
import io, re
s = io.open('docs/spec/css-color-4.html', encoding='utf-8').read()
pairs = re.findall(r'id="valdef-color-([a-z]+)">[a-z]+</dfn>\s*<td>#([0-9a-f]{6})', s)
seen = {}
for n, h in pairs:
    seen[n] = h
names = sorted(seen)
o = '//! Generated by tools/gen_colors.py from CSS Color 4 section 6.1 (named colors). Do not edit.\n\n'
o += '/// (name, 0xRRGGBB), sorted by name.\npub static NAMED_COLORS: &[(&str, u32)] = &[\n'
for n in names:
    o += '    ("%s", 0x%s),\n' % (n, seen[n])
o += '];\n'
io.open('crates/qinglan-engine/src/css/color_names.rs', 'w', encoding='utf-8', newline='\n').write(o)
print(len(names))
